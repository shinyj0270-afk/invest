'use strict';
const assert=require('node:assert/strict'),P=require('../src/comparison_price_ui.js');
const bars=Array.from({length:400},(_,i)=>({date:new Date(Date.UTC(2025,0,1)+i*86400000).toISOString().slice(0,10),close:100+i,final:true,volume:10}));
const copy=JSON.stringify(bars),m=P.analyze(bars,bars.at(-1).date);
assert.equal(m.ma50,474.5);assert.equal(m.ma200,399.5);assert.equal(m.rangeLabel,'52주 종가 범위');assert.equal(m.high,499);assert.equal(m.low,135);assert.equal(m.position,100);assert.equal(m.label,'상승 흐름');assert.equal(JSON.stringify(bars),copy);
assert.equal(P.analyze(bars.slice(0,126),bars[125].date).ma200,null);
assert.equal(P.analyze(bars,'bad').status,'unavailable');assert.equal(P.analyze([],bars[0].date).status,'unavailable');
assert.equal(P.analyze([...bars,bars[0]],bars.at(-1).date).status,'unavailable');
assert.equal(P.analyze([...bars.slice(0,-1),{...bars.at(-1),close:0}],bars.at(-1).date).status,'unavailable');
assert.equal(P.analyze(bars,bars[99].date).price,199);
assert.equal(P.analyze([{...bars[0],close:100}],bars[0].date).position,null);
assert.equal(P.analyze(bars.map(p=>({...p,close:100})),bars.at(-1).date).label,'추세 혼재');
assert.equal(P.analyze(bars.map(p=>({...p,close:600-p.close})),bars.at(-1).date).label,'추세 확인 우선');
assert.equal(P.analyze([...bars.slice(0,-1),{...bars.at(-1),close:700}],bars.at(-1).date).label,'추격 부담');
assert.equal(P.analyze([...bars.slice(0,-1),{...bars.at(-1),volume:0}],bars.at(-1).date).label,'거래 상태 확인');
const item={key:'per',value:10,median:20,count:5,period:'TTM',basis:'CFS',price_date:'2026-10-14'};
assert.equal(P.valuation([item,{...item,key:'pbr'}]).label,'상대 배수 낮음');
for(const change of [{count:4},{period:'unknown'},{basis:''},{price_date:'bad'},{value:-1},{median:null}])assert.equal(P.valuation([{...item,...change}]).label,'가치 비교 대기');
assert.equal(P.valuation([item]).label,'일부 배수만 비교 가능');
assert.equal(P.valuation([item,{...item,key:'pbr',value:30}]).label,'배수 신호 혼재');
const html=P.card({code:'1',name:'<img>'},m,P.valuation([]),63,'<script>','test');
assert(!html.includes('<img>'));assert(html.includes('&lt;script&gt;'));assert(html.includes('2026-02-04'));assert(html.includes('data-cp-series="ma200"'));
console.log('comparison price: calculations, missing data, valuation and escaping PASS');
